-- Module 20: the transactional outbox. Events are written in the same transaction as
-- the order and published to the broker afterwards by OutboxRelay.
create table outbox_events (
    id             bigint generated by default as identity primary key,
    aggregate_type varchar(50)  not null,
    aggregate_id   varchar(50)  not null,
    event_type     varchar(100) not null,
    payload        varchar(4000) not null,
    created_at     timestamp(6) with time zone not null,
    published_at   timestamp(6) with time zone
);
create index ix_outbox_unpublished on outbox_events (published_at, id);
