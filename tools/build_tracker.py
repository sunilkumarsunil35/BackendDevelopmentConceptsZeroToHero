#!/usr/bin/env python3
"""Builds the tracker's catalog from the lessons.

Every lesson in lessons/NN-name.md lists its topics as "### Title" headings under "## Concepts"
and "## Practice", each followed by a "**Level:** Beginner|Intermediate|Advanced" line and an
optional "**Code:** [file](path)" link. This script turns them into the CATALOG block inside
tracker/index.html, so the tracker always matches the lessons.

    python3 tools/build_tracker.py          # rewrite the catalog block
    python3 tools/build_tracker.py --check  # fail if the block is out of date (used in CI)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LESSONS = ROOT / "lessons"
TRACKER = ROOT / "tracker" / "index.html"
START, END = "// <catalog: generated by tools/build_tracker.py>", "// </catalog>"
LEVELS = {"Beginner": "B", "Intermediate": "I", "Advanced": "A"}

WEEK_TITLES = {
    1: "Java and HTTP foundations",
    2: "Maven and Spring Core",
    3: "Boot essentials, first REST API",
    4: "Validation, errors and SQL",
    5: "JPA and transactions",
    6: "Migrations and testing",
    7: "Security and JWT",
    8: "Caching, async, events, AOP",
    9: "Resilience, observability, API design",
    10: "Messaging and microservices",
    11: "Reactive, performance, scaling",
    12: "Deployment and capstone",
}


def github_slug(heading):
    """Same anchor GitHub generates for a Markdown heading."""
    s = heading.strip().lower()
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


def parse(path):
    text = path.read_text(encoding="utf-8")
    num = int(path.name[:2])
    title = re.search(r"^# \d+ · (.+)$", text, re.M).group(1).strip()
    header = re.search(r"^> \*\*Phase:\*\* (.+?) · \*\*Week:\*\* (\d+)", text, re.M)
    phase, week = header.group(1), int(header.group(2))
    items, section, seen = [], None, set()
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("## "):
            section = {"## Concepts": "concept", "## Practice": "practice"}.get(line.strip())
            continue
        if section and line.startswith("### "):
            heading = line[4:].strip()
            anchor = github_slug(heading)
            if anchor in seen:
                sys.exit(f"{path.name}: duplicate heading '{heading}'")
            seen.add(anchor)
            meta = lines[i + 1] if i + 1 < len(lines) else ""
            level = re.search(r"\*\*Level:\*\* (\w+)", meta)
            if not level or level.group(1) not in LEVELS:
                sys.exit(f"{path.name}: '{heading}' needs a '**Level:** Beginner|Intermediate|Advanced' line")
            code = re.search(r"\*\*Code:\*\* \[[^\]]+\]\(\.\./([^)#]+)\)", meta)
            items.append([section[0], heading, LEVELS[level.group(1)], anchor, code.group(1) if code else None])
    if not items:
        sys.exit(f"{path.name}: no topics found")
    return {"id": path.stem[3:], "num": num, "name": title, "phase": phase, "week": week,
            "file": path.name, "items": items}


def render(modules):
    weeks = {}
    for m in modules:
        weeks.setdefault(m["week"], []).append(m["id"])
    out = [START,
           "  // [id, number, name, phase, lesson file, items: [kind c|p, title, level B|I|A, anchor, code path|null]]",
           "  const CATALOG = ["]
    for m in modules:
        out.append(f"    [{json.dumps(m['id'])}, {m['num']}, {json.dumps(m['name'])}, {json.dumps(m['phase'])}, "
                   f"{json.dumps(m['file'])}, [")
        for it in m["items"]:
            out.append(f"      {json.dumps(it, ensure_ascii=False)},")
        out.append("    ]],")
    out.append("  ];")
    out.append("  // [week title, module ids]")
    out.append("  const WEEKS = [")
    for w in sorted(weeks):
        out.append(f"    [{json.dumps(WEEK_TITLES.get(w, 'Week ' + str(w)))}, {json.dumps(weeks[w])}],")
    out.append("  ];")
    out.append("  " + END)
    return "\n".join(out)


def main():
    modules = [parse(p) for p in sorted(LESSONS.glob("[0-9][0-9]-*.md"))]
    html = TRACKER.read_text(encoding="utf-8")
    start, end = html.index(START), html.index(END) + len(END)
    updated = html[:start] + render(modules) + html[end:]
    total = sum(len(m["items"]) for m in modules)
    if "--check" in sys.argv:
        if updated != html:
            sys.exit("tracker/index.html is out of date: run python3 tools/build_tracker.py")
        print(f"tracker is up to date: {len(modules)} modules, {total} topics")
        return
    TRACKER.write_text(updated, encoding="utf-8")
    print(f"wrote {len(modules)} modules, {total} topics to {TRACKER.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
